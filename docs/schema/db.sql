CREATE INDEX IF NOT EXISTS idx_mbkcore_sessions_expires ON mbkcore_sessions USING btree (expires_at) WHERE (expires_at IS NOT NULL);
CREATE INDEX IF NOT EXISTS idx_mbkcore_sessions_user_created ON mbkcore_sessions USING btree (username, created_at);
CREATE INDEX IF NOT EXISTS idx_mbkcore_sessions_username_expires ON mbkcore_sessions USING btree (username, expires_at);
COMMENT ON TABLE mbkcore_sessions IS '[core]';

-- Table: mbkcore_trusted_devices
CREATE TABLE IF NOT EXISTS mbkcore_trusted_devices (
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username character varying(50) NOT NULL REFERENCES mbkcore_users(username) ON DELETE CASCADE,
    device_token character varying(64) NOT NULL,
    device_name character varying(255),
    user_agent text,
    ip_address character varying(45),
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    expires_at timestamp with time zone NOT NULL,
    last_used timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT mbkcore_trusted_devices_pkey PRIMARY KEY (id),
    CONSTRAINT mbkcore_trusted_devices_device_token_key UNIQUE (device_token)
);
CREATE INDEX IF NOT EXISTS idx_mbkcore_trusted_devices_expires ON mbkcore_trusted_devices USING btree (expires_at);
CREATE INDEX IF NOT EXISTS idx_mbkcore_trusted_devices_username_expires ON mbkcore_trusted_devices USING btree (username, expires_at);
CREATE INDEX IF NOT EXISTS idx_mbkcore_trusted_devices_token_user_expires ON mbkcore_trusted_devices USING btree (device_token, username, expires_at);
COMMENT ON TABLE mbkcore_trusted_devices IS '[core]';

-- Table: mbkcore_two_factor
