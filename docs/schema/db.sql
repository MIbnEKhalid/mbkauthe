COMMENT ON TABLE mbkcore_two_factor IS '[core]';

-- Table: mbkcore_session (express-session store)
CREATE TABLE IF NOT EXISTS mbkcore_session (
    sid character varying NOT NULL,
    sess json NOT NULL,
    expire timestamp(6) without time zone NOT NULL,
    username character varying(50) REFERENCES mbkcore_users(username) ON DELETE CASCADE,
    last_activity timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT mbkcore_session_pkey PRIMARY KEY (sid)
);
CREATE INDEX IF NOT EXISTS idx_mbkcore_session_expire ON mbkcore_session USING btree (expire);
CREATE INDEX IF NOT EXISTS idx_mbkcore_session_last_activity ON mbkcore_session USING btree (last_activity);
CREATE INDEX IF NOT EXISTS idx_mbkcore_session_user_id ON mbkcore_session USING btree ((((sess -> 'user'::text) ->> 'id'::text)));
COMMENT ON TABLE mbkcore_session IS '[core]';

